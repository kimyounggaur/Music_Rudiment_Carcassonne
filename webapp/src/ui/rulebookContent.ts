const MVP = R.SETS.mvp;
const FULL = R.SETS.full;
const nTiles = (set: R.SetId, level: R.LevelId) => R.tileCount({ set, level });
const nBars = (set: R.SetId, level: R.LevelId) => R.barCount({ set, level });
const beatsOf = (k: KindId) => fmtBeats(R.SYMBOLS[R.kindOf(k).sym!].beats);
const nameOf = (k: KindId) => R.kindOf(k).name;
/** 그 타일이 처음 나오는 난이도 */
export const firstLevel = (k: KindId): R.LevelId => (k in R.LV2_ADD ? 2 : R.LEVELS[0].exclude.includes(k) ? 1 : 0);
const lvTag = (lv: R.LevelId) => `${R.LEVELS[lv].label.split(' ')[0]}부터`;

/** 박자값 표 (박자값·이름·난이도 모두 엔진에서) */
export const BEAT_KINDS: KindId[] = ['w-s', 'dh-s', 'h-s', 'q-s', 'dq-s', 'e-s', 'hr', 'qr', 'er'];
const beatRows = (kinds: KindId[]) => kinds.map((k) => [`**${nameOf(k)}**`, `${beatsOf(k)}박`, lvTag(firstLevel(k))]);

