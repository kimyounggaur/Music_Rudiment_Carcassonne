/* 룰북 내용 — 순수 데이터(React 없음).
 * 숫자(타일 수·박자값·난이도)는 엔진에서 가져와 글과 그림이 어긋나지 않게 하고,
 * 어느 그림이 어느 장 어디에 들어가는지는 여기서만 정한다 (그림 번호는 이 순서대로 매겨진다).
 *
 * 글 안의 표시:  **굵게**  ==형광펜==  [[장id 보여 줄 말]] (그 장으로 가는 링크) */
import * as R from '../engine/engine';
import type { KindId } from '../engine/engine';
import { fmtBeats } from '../art/tiles';
import type { FigId } from '../art/rulebookFigs';

export type NoteTone = 'tip' | 'warn' | 'rule' | 'why';

export type Block =
  | { t: 'p'; s: string }
  | { t: 'h'; s: string }
  | { t: 'ul'; items: string[] }
  | { t: 'ol'; items: string[] }
  | { t: 'steps'; items: Array<{ title: string; s: string }> }
  | { t: 'fig'; id: FigId; cap: string }
  | { t: 'note'; tone: NoteTone; title?: string; s: string }
  | { t: 'table'; head: string[]; rows: string[][]; label: string }
  | { t: 'facts'; items: Array<{ k: string; v: string }> }
  | { t: 'cfg' }
  | { t: 'skin' }
  | { t: 'actions'; items: Array<'tutorial' | 'puzzles'> }
  | { t: 'faq'; items: Array<{ q: string; body: Block[] }> };

export interface Chapter {
  id: string;
  no: number;
  title: string;
  /** 작은 화면 목차 칩에 쓰는 짧은 이름 */
  short: string;
  lead: string;
  /** 이 장 규칙이 쓰이는 난이도 (표시용) */
  lv?: R.LevelId;
  blocks: Block[];
}

// ── 엔진에서 가져온 숫자 ─────────────────────────────────────────────
const HAND = R.DEFAULT_CFG.handSize;
