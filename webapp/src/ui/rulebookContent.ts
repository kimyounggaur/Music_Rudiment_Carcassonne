export const chapterById = (id: string): Chapter | undefined => CHAPTERS.find((c) => c.id === id);

/** 장 안의 모든 블록 (FAQ 안쪽 블록까지 펼쳐서) */
export function* walkBlocks(blocks: Block[]): Generator<Block> {
  for (const b of blocks) {
    yield b;
    if (b.t === 'faq') for (const it of b.items) yield* walkBlocks(it.body);
  }
}

/** 룰북에 나오는 순서대로의 그림 id */
export const FIG_ORDER: FigId[] = CHAPTERS.flatMap((c) => [...walkBlocks(c.blocks)].filter((b): b is Extract<Block, { t: 'fig' }> => b.t === 'fig').map((b) => b.id));
/** 그림 번호 (1부터) — 장이 달라도 이어서 센다 */
export const FIG_NO: Record<string, number> = Object.fromEntries(FIG_ORDER.map((id, i) => [id, i + 1]));
export const FIG_CAP: Record<string, string> = Object.fromEntries(
  CHAPTERS.flatMap((c) => [...walkBlocks(c.blocks)].filter((b): b is Extract<Block, { t: 'fig' }> => b.t === 'fig').map((b) => [b.id, b.cap] as const)),
);

/** 글 안의 표시를 조각으로 나눈다: 굵게 · 형광펜 · 장 링크 */
export type InlinePart = { k: 'text' | 'b' | 'mark'; s: string } | { k: 'ref'; id: string; s: string };
export function parseInline(s: string): InlinePart[] {
  const out: InlinePart[] = [];
  const re = /\*\*(.+?)\*\*|==(.+?)==|\[\[(\w+) (.+?)\]\]/g;
  let last = 0;
  for (let m = re.exec(s); m; m = re.exec(s)) {
    if (m.index > last) out.push({ k: 'text', s: s.slice(last, m.index) });
    if (m[1] != null) out.push({ k: 'b', s: m[1] });
    else if (m[2] != null) out.push({ k: 'mark', s: m[2] });
    else out.push({ k: 'ref', id: m[3], s: m[4] });
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push({ k: 'text', s: s.slice(last) });
  return out;
}
